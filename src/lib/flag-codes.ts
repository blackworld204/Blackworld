export function resolveFlagCountry(code: string): string | null {
  const raw = code.trim();
  if (!raw) return null;
  const upper = raw.toUpperCase();
  const lower = raw.toLowerCase();

  // ISO currencies are three letters (NGN → Nigeria). Check them first.
  const fromCurrency = CURRENCY_TO_FLAG[upper];
  if (fromCurrency) return fromCurrency;

  // Country / dial codes are passed uppercase (NG). Language ids are lowercase (ca, en).
  // Prefer the country when the caller used uppercase so Nigeria is not read as Ndonga → Namibia.
  if (/^[A-Z]{2}$/.test(raw) && COUNTRY_FLAGS.has(upper)) return upper;

  const fromLanguage = LANGUAGE_TO_FLAG[lower];
  if (fromLanguage) return fromLanguage;

  if (COUNTRY_FLAGS.has(upper)) return upper;

  return null;
}

export function flagEmoji(country: string): string {
  const cc = country.toUpperCase();
  if (cc === "EU") return "🇪🇺";
  if (cc === "UN") return "🇺🇳";
  if (!/^[A-Z]{2}$/.test(cc)) return "";
  return [...cc].map((char) => String.fromCodePoint(127397 + char.charCodeAt(0))).join("");
}

export function flagImageUrl(country: string, width = 40): string {
  return `https://flagcdn.com/w${width}/${country.toLowerCase()}.png`;
}
