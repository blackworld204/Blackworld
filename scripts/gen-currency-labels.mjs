src = src.replace(/\nexport const CURRENCY_LABELS: Record<string, string> = \{[\s\S]*?\};\n/, "\n");

const block = `
/** Everyday unit names shown in selectors (flag still disambiguates shared names). */
export const CURRENCY_LABELS: Record<string, string> = ${JSON.stringify(SHORT, null, 2)};

/** Short everyday unit name for selectors and kickers (Naira, Rupees, Dollar…). */
export function currencyLabel(code: string, _name?: string) {
  return CURRENCY_LABELS[code] ?? code;
}
`;

if (!src.includes("export function findCurrency")) {
  throw new Error("findCurrency missing");
}
src = src.replace("export function findCurrency", `${block}\nexport function findCurrency`);
writeFileSync(path, src);
